export function renderLegacyPoemList(containerId = "poemList") {
    if (typeof window === "undefined") return;
    const poemList = document.getElementById(containerId);
    if (!poemList) return;

    poems.forEach((poem) => {
        const div = document.createElement("div");
        div.className = "p-4 border rounded-lg shadow hover:bg-gray-50 dark:hover:bg-[#1a1a1a] cursor-pointer";
        div.innerHTML = `
      <h3 class="text-xl font-semibold mb-1">${poem.title}</h3>
      <p class="text-sm text-gray-500 dark:text-gray-400 mb-2">${poem.date}</p>
      <div class="flex flex-wrap gap-2 text-xs mb-2">
        ${poem.tags.map(tag => `<span class='bg-accent text-white px-2 py-1 rounded-full'>${tag}</span>`).join(" ")}
      </div>
      <p class="text-sm italic text-gray-600 dark:text-gray-300">Click to read</p>
    `;
        poemList.appendChild(div);
    });
}
